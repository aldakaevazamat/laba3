import math


def calculate_y(x):
    """
    Функция для вычисления Y по графику (Вариант 2).
    Ветви программы соответствуют участкам графика.
    """
    if x < -8:
        # 1. Горизонтальная прямая слева на уровне y = -3
        return -3
    elif -8 <= x < -3:
        # 2. Наклонная прямая от (-8, -3) до (-3, 3)
        # k = (3 - (-3)) / (-3 - (-8)) = 6/5 = 1.2
        # 3 = 1.2*(-3) + b => b = 6.6
        return 1.2 * x + 6.6
    elif -3 <= x <= 3:
        # 3. Нижняя полуокружность с центром (0,0), R=3
        return -math.sqrt(9 - x ** 2)
    elif 3 < x < 5:
        # 4. Наклонная прямая от (3, 0) до (5, 3)
        # k = (3-0)/(5-3) = 1.5
        # 0 = 1.5*3 + b => b = -4.5
        return 1.5 * x - 4.5
    else:  # x >= 5
        # 5. Горизонтальная прямая справа на уровне y = 3
        return 3


def main():
    print("Лабораторная работа №3. Задание 1 (Вариант 2)")
    print("Вычисление значений функции в виде таблицы\n")

    # --- Ввод данных ---
    try:
        x_start = float(input("Введите Xнач (начало интервала): "))
        x_end = float(input("Введите Xкон (конец интервала): "))
        dx = float(input("Введите dx (шаг): "))

        if dx <= 0:
            print("Ошибка: Шаг (dx) должен быть положительным числом.")
            return
        if x_start > x_end:
            print("Ошибка: Начало интервала не может быть больше конца.")
            return

    except ValueError:
        print("Ошибка ввода: пожалуйста, вводите числа.")
        return

    # --- Вывод шапки таблицы ---
    print("-" * 35)
    print(f"| {'X':^12} | {'Y':^18} |")
    print("-" * 35)

    # --- Организация цикла ---
    x = x_start
    # Используем while, так как шаг задается пользователем (дробный)
    # 1e-9 нужен для компенсации погрешности float при сложении
    while x <= x_end + 1e-9:
        y = calculate_y(x)

        # Вывод строки таблицы
        print(f"| {x:12.4f} | {y:18.4f} |")

        x += dx

    print("-" * 35)


if __name__ == "__main__":
    main()