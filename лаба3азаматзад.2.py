import random
import math


def main():
    print("--- Лабораторная работа №3. Задание 2 (Мишень №2) ---")

    # Запрашиваем радиус у пользователя.
    # Если пользователь введет не число, программа попросит ввести заново.
    while True:
        try:
            R = float(input("Введите радиус мишени R (например, 10, 5.5 или 100): "))
            if R > 0:
                break
            else:
                print("Радиус должен быть больше нуля!")
        except ValueError:
            print("Ошибка! Пожалуйста, введите число.")

    shots_count = 10

    print(f"\n--- Начинаем {shots_count} выстрелов по мишени с радиусом R = {R} ---")

    # Цикл для 10 выстрелов
    for i in range(1, shots_count + 1):
        # Генерируем случайные координаты X и Y в диапазоне от -R до R
        x = random.uniform(-R, R)
        y = random.uniform(-R, R)

        is_hit = False

        # --- ПРОВЕРКА УСЛОВИЙ ПОПАДАНИЯ (они универсальны для любого R) ---

        # 1. Левая верхняя часть (четверть круга)
        if x <= 0 and y >= 0 and (x ** 2 + y ** 2) <= R ** 2:
            is_hit = True

        # 2. Правая нижняя часть (треугольник)
        elif x >= 0 and y <= 0 and x <= R and y >= (x - R):
            is_hit = True

        # --- ВЫВОД РЕЗУЛЬТАТА ---
        # Округляем координаты до 2 знаков для красоты вывода
        x_round = round(x, 2)
        y_round = round(y, 2)

        if is_hit:
            print(f"Выстрел {i:2}: Координаты (X={x_round:6}, Y={y_round:6}) -> ПОПАДАНИЕ!")
        else:
            print(f"Выстрел {i:2}: Координаты (X={x_round:6}, Y={y_round:6}) -> промах.")

    print("\n--- Стрельба завершена ---")


if __name__ == "__main__":
    main()